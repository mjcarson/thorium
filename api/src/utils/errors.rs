/// Convert [`ApiError`] into an [`rmcp::ErrorData`]
impl From<ApiError> for rmcp::ErrorData {
    /// Cast an ApiError into an rmcp error
    ///
    /// # Arguments
    ///
    /// * `error` - The ApiError to convert to an rmcp error
    fn from(error: ApiError) -> Self {
        // emit an event with the full info since this path skips into_response
        let span = span!(Level::ERROR, "Error Message");
        event!(parent: &span, Level::ERROR, kind = error.kind(), msg = error.msg());
        // get the status code for this error
        let status = error.status();
        // get the message that is safe to expose or fall back to a generic one
        let message = match error.public_msg() {
            // this message is safe to expose
            Some(msg) => msg,
            // abstract internal server errors to a generic message
            None if status.is_server_error() => "an internal server error occurred".to_owned(),
            // this error has no message to expose
            None => "Unknown Error".to_owned(),
        };
        // map our return code to an rmcp error code
        let code = match status {
            StatusCode::NOT_FOUND => rmcp::model::ErrorCode::RESOURCE_NOT_FOUND,
            StatusCode::BAD_REQUEST => rmcp::model::ErrorCode::INVALID_REQUEST,
            _ => rmcp::model::ErrorCode::INTERNAL_ERROR,
        };
        // build our rmcp error
        rmcp::ErrorData {
            code,
            message: message.into(),
            data: None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Get the body of a response as a string
    ///
    /// # Arguments
    ///
    /// * `response` - The response to extract a body from
    async fn body_string(response: Response) -> String {
        // read the full body of this response
        let bytes = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .expect("Failed to read response body");
        // cast our body to a string
        String::from_utf8(bytes.to_vec()).expect("Response body was not utf8")
    }

    /// Build a Redis error containing a secret internal detail
    fn redis_error() -> bb8_redis::redis::RedisError {
        bb8_redis::redis::RedisError::from((
            bb8_redis::redis::ErrorKind::IoError,
            "io error",
            "secret internal detail".to_owned(),
        ))
    }

    #[tokio::test]
    async fn thorium_errors_expose_their_message() {
        // build a Thorium generated error
        let error: Result<(), ApiError> = bad!("Corn must be shucked!".to_owned());
        // build a response from this error
        let response = error.unwrap_err().into_response();
        // make sure the status code and message are exposed
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        assert!(body_string(response).await.contains("Corn must be shucked!"));
    }

    #[tokio::test]
    async fn parse_errors_expose_their_message() {
        // build an error from parsing user provided data
        let error = ApiError::from(uuid::Uuid::try_parse("not-a-uuid").unwrap_err());
        // build a response from this error
        let response = error.into_response();
        // make sure the status code and message are exposed
        assert_eq!(response.status(), StatusCode::BAD_REQUEST);
        assert!(body_string(response).await.contains("Failed cast to Uuid"));
    }

    #[tokio::test]
    async fn redis_errors_are_hidden() {
        // build an internal Redis error with a secret detail
        let error = ApiError::from(redis_error());
        // make sure the full info is still available for tracing events
        assert!(error.msg().unwrap().contains("secret internal detail"));
        // build a response from this error
        let response = error.into_response();
        // make sure this error was abstracted to a generic 500
        assert_eq!(response.status(), StatusCode::INTERNAL_SERVER_ERROR);
        let body = body_string(response).await;
        assert!(body.contains("an internal server error occurred"));
        assert!(!body.contains("secret internal detail"));
    }

    #[tokio::test]
    async fn serde_errors_are_hidden() {
        // build an internal serde error
        let error = ApiError::from(serde_json::from_str::<u32>("bad json").unwrap_err());
        // build a response from this error
        let response = error.into_response();
        // make sure this error was abstracted to a generic 500
        assert_eq!(response.status(), StatusCode::INTERNAL_SERVER_ERROR);
        let body = body_string(response).await;
        assert!(body.contains("an internal server error occurred"));
        assert!(!body.contains("bad json"));
    }

    #[tokio::test]
    async fn oauth_errors_are_bare_401s() {
        // build an internal OAuth error with a secret detail
        let error = ApiError::OAuth("secret oauth detail".to_owned());
        // build a response from this error
        let response = error.into_response();
        // make sure this error is a 401 with no error message
        assert_eq!(response.status(), StatusCode::UNAUTHORIZED);
        assert!(!body_string(response).await.contains("secret oauth detail"));
    }

    #[test]
    fn accessors_follow_the_exposure_policy() {
        // build one error of each exposure class
        let thorium = ApiError::new(StatusCode::CONFLICT, Some("already exists".to_owned()));
        let parse = ApiError::from(uuid::Uuid::try_parse("not-a-uuid").unwrap_err());
        let hidden = ApiError::from(redis_error());
        let oauth = ApiError::OAuth("secret oauth detail".to_owned());
        // make sure the status codes are correct
        assert_eq!(thorium.status(), StatusCode::CONFLICT);
        assert_eq!(parse.status(), StatusCode::BAD_REQUEST);
        assert_eq!(hidden.status(), StatusCode::INTERNAL_SERVER_ERROR);
        assert_eq!(oauth.status(), StatusCode::UNAUTHORIZED);
        // make sure only safe messages are exposed
        assert_eq!(thorium.public_msg(), Some("already exists".to_owned()));
        assert!(parse.public_msg().is_some());
        assert_eq!(hidden.public_msg(), None);
        assert_eq!(oauth.public_msg(), None);
        // make sure the kinds are correct
        assert_eq!(thorium.kind(), "Thorium");
        assert_eq!(parse.kind(), "Uuid");
        assert_eq!(hidden.kind(), "Redis");
        assert_eq!(oauth.kind(), "OAuth");
    }

    #[test]
    fn rmcp_errors_follow_the_exposure_policy() {
        // build an internal Redis error with a secret detail
        let hidden = rmcp::ErrorData::from(ApiError::from(redis_error()));
        // make sure this error was abstracted to a generic internal error
        assert_eq!(hidden.code, rmcp::model::ErrorCode::INTERNAL_ERROR);
        assert_eq!(hidden.message, "an internal server error occurred");
        // build a Thorium generated error
        let thorium: Result<(), ApiError> = bad!("Corn must be shucked!".to_owned());
        let exposed = rmcp::ErrorData::from(thorium.unwrap_err());
        // make sure the message is exposed for Thorium errors
        assert_eq!(exposed.code, rmcp::model::ErrorCode::INVALID_REQUEST);
        assert_eq!(exposed.message, "Corn must be shucked!");
    }
}
