/// An error from the Thorium API
///
/// Only `Thorium` errors and errors from parsing user provided data may
/// expose their messages to users. All other variants are abstracted to a
/// generic error response while their full info is emitted as a tracing
/// event. Never embed the output of [`ApiError::msg`] or this types `Display`
/// impl into a user visible `Thorium` message as that could leak internal
/// info.
#[derive(Debug)]
pub enum ApiError {
    /// An error generated by Thorium itself
    ///
    /// These messages are always safe to expose to users.
    Thorium {
        /// The status code to return
        code: StatusCode,
        /// The error message to return
        msg: Option<String>,
    },
    /// A user tried to build an enum from an invalid value
    InvalidEnum(InvalidEnum),
    /// An error from converting user provided values
    Conversion(ConversionError),
    /// An error from parsing a Uuid
    Uuid(uuid::Error),
    /// An error from parsing an int
    ParseInt(std::num::ParseIntError),
    /// An error from parsing a float
    ParseFloat(std::num::ParseFloatError),
    /// An error from parsing a bool
    ParseBool(std::str::ParseBoolError),
    /// An error from parsing a timestamp/date
    ChronoParse(chrono::format::ParseError),
    /// An error from base64 decoding a string
    Base64Decode(base64::DecodeError),
    /// An error from casting bytes to a utf8 formatted str
    Utf8(std::str::Utf8Error),
    /// An error from parsing a URL
    UrlParse(url::ParseError),
    /// An error from casting an int
    TryFromInt(std::num::TryFromIntError),
    /// An error from extracting a multipart form
    Multipart(axum::extract::multipart::MultipartError),
    /// An error from deserializing query params
    SerdeQs(serde_qs::Error),
    /// An error from deserializing user provided yaml
    SerdeYaml(serde_norway::Error),
    /// An error from parsing a semver version
    Semver(semver::Error),
    /// An error from parsing an IP address
    AddrParse(std::net::AddrParseError),
    /// An error from parsing an enum variant with strum
    StrumParse(strum::ParseError),
    /// An error from parsing a country code
    CountryCode(isocountry::CountryCodeParseErr),
    /// An error from decoding a user uploaded CaRT file
    Cart(cart_rs::Error),
    /// An error from converting a value with serde
    Serde(serde_json::Error),
    /// An IO error
    IO(std::io::Error),
    /// An error from hashing with argon2
    Argon2(argon2::Error),
    /// An error from hashing a password with argon2
    PasswordHash(argon2::password_hash::Error),
    /// An error from talking to LDAP
    Ldap(ldap3::result::LdapError),
    /// An error from anyhow
    Anyhow(anyhow::Error),
    /// An error from an elastic client
    Elastic(elasticsearch::Error),
    /// An error from an elastic response
    ///
    /// This error is boxed because it is large enough to bloat the size of
    /// every `Result` containing an [`ApiError`].
    ElasticResponse(Box<elasticsearch::http::response::Error>),
    /// An error from the Redis backend
    Redis(bb8_redis::redis::RedisError),
    /// An error from executing a Scylla query
    ///
    /// This error is boxed because it is large enough to bloat the size of
    /// every `Result` containing an [`ApiError`].
    ScyllaExecution(Box<scylla::errors::ExecutionError>),
    /// An error from converting a Scylla query result into rows
    ///
    /// This error is boxed because it is large enough to bloat the size of
    /// every `Result` containing an [`ApiError`].
    ScyllaIntoRowsResult(Box<scylla::response::query_result::IntoRowsResultError>),
    /// An error from getting rows from a Scylla query result
    ScyllaRows(scylla::response::query_result::RowsError),
    /// An error from deserializing a Scylla row
    ScyllaDeserialization(scylla::deserialize::DeserializationError),
    /// An error from getting the first row of a Scylla query result
    ScyllaMaybeFirstRow(scylla::response::query_result::MaybeFirstRowError),
    /// An error from getting the next row from a Scylla pager
    ScyllaNextRow(scylla::client::pager::NextRowError),
    /// An error from executing a paged Scylla query
    ///
    /// This error is boxed because it is large enough to bloat the size of
    /// every `Result` containing an [`ApiError`].
    ScyllaPagerExecution(Box<scylla::errors::PagerExecutionError>),
    /// An error from type checking a Scylla row
    ScyllaTypeCheck(scylla::deserialize::TypeCheckError),
    /// An error from talking to S3
    S3 {
        /// The S3 action that failed
        action: &'static str,
        /// The error S3 returned
        error: Box<dyn std::error::Error + Send + Sync + 'static>,
    },
    /// An error from joining a tokio task
    TokioJoin(tokio::task::JoinError),
    /// An error from zipping a file
    Zip(zip::result::ZipError),
    /// An error from authenticating with OAuth
    OAuth(String),
}

impl ApiError {
    /// Creates a new Thorium error
    ///
    /// # Arguments
    ///
    /// * `code` - The status of the error response
    /// * `msg` - The message to put in the response
    #[must_use]
    pub fn new(code: StatusCode, msg: Option<String>) -> ApiError {
        ApiError::Thorium { code, msg }
    }

    /// Get the status code to return for this error
    #[must_use]
    pub fn status(&self) -> StatusCode {
        match self {
            // Thorium errors carry their own status code
            ApiError::Thorium { code, .. } => *code,
            // errors from parsing user provided data are bad requests
            ApiError::InvalidEnum(_)
            | ApiError::Conversion(_)
            | ApiError::Uuid(_)
            | ApiError::ParseInt(_)
            | ApiError::ParseFloat(_)
            | ApiError::ParseBool(_)
            | ApiError::ChronoParse(_)
            | ApiError::Base64Decode(_)
            | ApiError::Utf8(_)
            | ApiError::UrlParse(_)
            | ApiError::TryFromInt(_)
            | ApiError::Multipart(_)
            | ApiError::SerdeQs(_)
            | ApiError::SerdeYaml(_)
            | ApiError::Semver(_)
            | ApiError::AddrParse(_)
            | ApiError::StrumParse(_)
            | ApiError::CountryCode(_)
            | ApiError::Cart(_) => StatusCode::BAD_REQUEST,
            // failed OAuth authentications are unauthorized
            ApiError::OAuth(_) => StatusCode::UNAUTHORIZED,
            // all other errors are abstracted internal server errors
            _ => StatusCode::INTERNAL_SERVER_ERROR,
        }
    }

    /// Get the full message for this error
    ///
    /// This may contain internal info so it must only be used for tracing
    /// events and logs and never in user visible messages. Use
    /// [`ApiError::public_msg`] when building responses instead.
    #[must_use]
    pub fn msg(&self) -> Option<String> {
        match self {
            ApiError::Thorium { msg, .. } => msg.clone(),
            ApiError::InvalidEnum(error) => Some(error.to_string()),
            ApiError::Conversion(error) => Some(format!("Unable to convert value {error:#?}")),
            ApiError::Uuid(error) => Some(format!("Failed cast to Uuid {error:#?}")),
            ApiError::ParseInt(error) => Some(format!("Failed cast to int {error:#?}")),
            ApiError::ParseFloat(error) => Some(format!("Failed cast to float {error:#?}")),
            ApiError::ParseBool(error) => Some(format!("Failed cast to bool {error:#?}")),
            ApiError::ChronoParse(error) => Some(format!("Failed to parse timestamp {error:#?}")),
            ApiError::Base64Decode(error) => {
                Some(format!("Failed to base64 decode string {error:#?}"))
            }
            ApiError::Utf8(error) => Some(format!("Failed to cast str to Utf8 {error:#?}")),
            ApiError::UrlParse(error) => Some(format!("URL parse error {error:#?}")),
            ApiError::TryFromInt(error) => Some(format!("Int casting error {error:#?}")),
            ApiError::Multipart(error) => {
                Some(format!("Failed to extract multipart form {error:#?}"))
            }
            ApiError::SerdeQs(error) => {
                Some(format!("Failed to deserialize query params {error:#?}"))
            }
            ApiError::SerdeYaml(error) => Some(format!("Failed to deserialize yaml {error:#?}")),
            ApiError::Semver(error) => Some(format!("Invalid semver version: {error:#?}")),
            ApiError::AddrParse(error) => Some(format!("Error parsing IP address: {error}")),
            ApiError::StrumParse(error) => Some(format!("Failed to parse variant: {error}")),
            ApiError::CountryCode(error) => {
                Some(format!("Failed to parse country code: {error}"))
            }
            ApiError::Cart(error) => Some(format!("Cart error {error:#?}")),
            ApiError::Serde(error) => Some(format!("Failed cast JsonValue to String {error:#?}")),
            ApiError::IO(error) => Some(format!("IO Error {error:#?}")),
            ApiError::Argon2(error) => Some(format!("Argon2 error {error:#?}")),
            ApiError::PasswordHash(error) => Some(format!("Argon2 password error {error:#?}")),
            ApiError::Ldap(error) => Some(format!("ldap error {error:#?}")),
            ApiError::Anyhow(error) => Some(format!("Anyhow error {error:#?}")),
            ApiError::Elastic(error) => Some(format!("Elasticsearch error {error:#?}")),
            ApiError::ElasticResponse(error) => Some(format!("Elasticsearch error {error:#?}")),
            ApiError::Redis(error) => Some(format!("Redis backend failure: {error:#?}")),
            ApiError::ScyllaExecution(error) => Some(format!("Scylla query error: {error:#?}")),
            ApiError::ScyllaIntoRowsResult(error) => {
                Some(format!("Scylla into rows error {error:#?}"))
            }
            ApiError::ScyllaRows(error) => Some(format!("Scylla rows error {error:#?}")),
            ApiError::ScyllaDeserialization(error) => {
                Some(format!("Scylla deserialization error {error:#?}"))
            }
            ApiError::ScyllaMaybeFirstRow(error) => {
                Some(format!("Scylla maybe first row error {error:#?}"))
            }
            ApiError::ScyllaNextRow(error) => Some(format!("Scylla next row error {error:#?}")),
            ApiError::ScyllaPagerExecution(error) => {
                Some(format!("Scylla pager execution error {error:#?}"))
            }
            ApiError::ScyllaTypeCheck(error) => {
                Some(format!("Scylla type check error {error:#?}"))
            }
            ApiError::S3 { action, error } => Some(format!("Failed to {action} {error:#?}")),
            ApiError::TokioJoin(error) => Some(format!("Tokio task failed to join: {error:#?}")),
            ApiError::Zip(error) => Some(format!("Failed to zip file: {error:#?}")),
            ApiError::OAuth(msg) => Some(msg.clone()),
        }
    }

    /// Get the message that is safe to expose to users for this error
    ///
    /// Only Thorium generated errors and errors from parsing user provided
    /// data return a message. All internal errors return `None` so their
    /// details are never leaked to users.
    #[must_use]
    pub fn public_msg(&self) -> Option<String> {
        match self {
            // Thorium generated messages are always safe to expose
            ApiError::Thorium { msg, .. } => msg.clone(),
            // errors from parsing user provided data are safe to expose
            ApiError::InvalidEnum(_)
            | ApiError::Conversion(_)
            | ApiError::Uuid(_)
            | ApiError::ParseInt(_)
            | ApiError::ParseFloat(_)
            | ApiError::ParseBool(_)
            | ApiError::ChronoParse(_)
            | ApiError::Base64Decode(_)
            | ApiError::Utf8(_)
            | ApiError::UrlParse(_)
            | ApiError::TryFromInt(_)
            | ApiError::Multipart(_)
            | ApiError::SerdeQs(_)
            | ApiError::SerdeYaml(_)
            | ApiError::Semver(_)
            | ApiError::AddrParse(_)
            | ApiError::StrumParse(_)
            | ApiError::CountryCode(_)
            | ApiError::Cart(_) => self.msg(),
            // all other errors are internal and must never be exposed
            _ => None,
        }
    }

    /// Get the kind of error as a str
    #[must_use]
    pub fn kind(&self) -> &'static str {
        match self {
            ApiError::Thorium { .. } => "Thorium",
            ApiError::InvalidEnum(_) => "InvalidEnum",
            ApiError::Conversion(_) => "Conversion",
            ApiError::Uuid(_) => "Uuid",
            ApiError::ParseInt(_) => "ParseInt",
            ApiError::ParseFloat(_) => "ParseFloat",
            ApiError::ParseBool(_) => "ParseBool",
            ApiError::ChronoParse(_) => "ChronoParse",
            ApiError::Base64Decode(_) => "Base64Decode",
            ApiError::Utf8(_) => "Utf8",
            ApiError::UrlParse(_) => "UrlParse",
            ApiError::TryFromInt(_) => "TryFromInt",
            ApiError::Multipart(_) => "Multipart",
            ApiError::SerdeQs(_) => "SerdeQs",
            ApiError::SerdeYaml(_) => "SerdeYaml",
            ApiError::Semver(_) => "Semver",
            ApiError::AddrParse(_) => "AddrParse",
            ApiError::StrumParse(_) => "StrumParse",
            ApiError::CountryCode(_) => "CountryCode",
            ApiError::Cart(_) => "Cart",
            ApiError::Serde(_) => "Serde",
            ApiError::IO(_) => "IO",
            ApiError::Argon2(_) => "Argon2",
            ApiError::PasswordHash(_) => "PasswordHash",
            ApiError::Ldap(_) => "Ldap",
            ApiError::Anyhow(_) => "Anyhow",
            ApiError::Elastic(_) => "Elastic",
            ApiError::ElasticResponse(_) => "ElasticResponse",
            ApiError::Redis(_) => "Redis",
            ApiError::ScyllaExecution(_) => "ScyllaExecution",
            ApiError::ScyllaIntoRowsResult(_) => "ScyllaIntoRowsResult",
            ApiError::ScyllaRows(_) => "ScyllaRows",
            ApiError::ScyllaDeserialization(_) => "ScyllaDeserialization",
            ApiError::ScyllaMaybeFirstRow(_) => "ScyllaMaybeFirstRow",
            ApiError::ScyllaNextRow(_) => "ScyllaNextRow",
            ApiError::ScyllaPagerExecution(_) => "ScyllaPagerExecution",
            ApiError::ScyllaTypeCheck(_) => "ScyllaTypeCheck",
            ApiError::S3 { .. } => "S3",
            ApiError::TokioJoin(_) => "TokioJoin",
            ApiError::Zip(_) => "Zip",
            ApiError::OAuth(_) => "OAuth",
        }
    }
}

impl fmt::Display for ApiError {
    /// Cast this error to either a string based on the message or the code
    ///
    /// This may contain internal info so it must never be embedded into a
    /// user visible `Thorium` message.
    ///
    /// # Arguments
    ///
    /// * `f` - The formatter that is being used
    fn fmt(&self, f: &mut fmt::Formatter) -> fmt::Result {
        match self.msg() {
            Some(msg) => write!(f, "{msg}"),
            // if we have a status code then return that and the reason if one exists
            None => write!(f, "code {} - {}", self.status().as_u16(), self.status()),
        }
    }
}

// mark that this is an error struct
impl std::error::Error for ApiError {}

/// The JSON body returned for API errors
#[derive(Debug, Serialize, ToSchema)]
pub struct ApiErrorResponse {
    /// The error message if one can be exposed
    #[serde(skip_serializing_if = "Option::is_none")]
    pub error: Option<String>,
    /// The trace id for correlating this error with server side traces
    #[serde(skip_serializing_if = "Option::is_none")]
    pub trace: Option<String>,
}

impl IntoResponse for ApiError {
    /// Allow Axum to build a response from error messages
    fn into_response(self) -> Response {
        // get our trace id
        let trace = trace::get_trace();
        // emit an event with the full info for this error
        let span = span!(Level::ERROR, "Error Message");
        event!(parent: &span, Level::ERROR, kind = self.kind(), msg = self.msg());
        // get the status code to return for this error
        let code = self.status();
        // get the message that is safe to expose to users
        let error = match self.public_msg() {
            // this message is safe to expose
            Some(msg) => Some(msg),
            // abstract internal server errors to a generic message
            None if code.is_server_error() => {
                Some("an internal server error occurred".to_owned())
            }
            // this error has no message to expose
            None => None,
        };
        // build our error response
        match (&error, &trace) {
            // we have no message or trace id so just return a status code
            (None, None) => code.into_response(),
            // return our error message and/or trace id
            _ => (code, Json(ApiErrorResponse { error, trace })).into_response(),
        }
    }
}

